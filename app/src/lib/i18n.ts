export const DICTS: Record<Lang, Record<Key, string>> = { en, pt };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'pt') return saved;
  } catch {
    // No storage: fall back to the browser language.
  }
  const nav = typeof navigator === 'undefined' ? '' : navigator.language || '';
  return nav.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

let current: Lang = initialLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    // Private mode: the choice lasts until the app closes.
  }
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  listeners.forEach((l) => l());
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (l) => {
      listeners.add(l);
      return () => void listeners.delete(l);
    },
    getLang,
    getLang,
  );
}

/** The text for a key in the current language, with {name} placeholders filled in. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const text = DICTS[current][key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}

/** The locale for dates in the current language. */
export function dateLocale(): string | undefined {
  return current === 'pt' ? 'pt-BR' : undefined;
}
